-- Premium-Member admin schema. PostgreSQL 17+.

CREATE TABLE IF NOT EXISTS sys_dept (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT      NOT NULL DEFAULT 0,
    name        VARCHAR(64) NOT NULL,
    leader      VARCHAR(64) NOT NULL DEFAULT '',
    phone       VARCHAR(32) NOT NULL DEFAULT '',
    sort        INTEGER     NOT NULL DEFAULT 0,
    status      SMALLINT    NOT NULL DEFAULT 1 CHECK (status IN (0, 1)),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted     SMALLINT    NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1))
);
CREATE INDEX IF NOT EXISTS idx_sys_dept_parent ON sys_dept (parent_id);

CREATE TABLE IF NOT EXISTS sys_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    real_name     VARCHAR(64)  NOT NULL,
    avatar        VARCHAR(512) NOT NULL DEFAULT '',
    description   VARCHAR(255) NOT NULL DEFAULT '',
    home_path     VARCHAR(128) NOT NULL DEFAULT '/analytics',
    email         VARCHAR(128),
    phone         VARCHAR(32),
    dept_id       BIGINT,
    status        SMALLINT     NOT NULL DEFAULT 1 CHECK (status IN (0, 1)),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted       SMALLINT     NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1))
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_user_username
    ON sys_user (username) WHERE deleted = 0;
CREATE INDEX IF NOT EXISTS idx_sys_user_dept ON sys_user (dept_id);

CREATE TABLE IF NOT EXISTS sys_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64) NOT NULL,
    name        VARCHAR(64) NOT NULL,
    data_scope  VARCHAR(16) NOT NULL DEFAULT 'SELF',
    status      SMALLINT    NOT NULL DEFAULT 1 CHECK (status IN (0, 1)),
    sort        INTEGER     NOT NULL DEFAULT 0,
    remark      VARCHAR(255) NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted     SMALLINT    NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1)),
    CONSTRAINT ck_sys_role_data_scope CHECK (data_scope IN ('ALL', 'DEPT_AND_CHILD', 'DEPT', 'SELF'))
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_role_code
    ON sys_role (code) WHERE deleted = 0;

ALTER TABLE sys_role ADD COLUMN IF NOT EXISTS data_scope VARCHAR(16) NOT NULL DEFAULT 'SELF';
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_sys_role_data_scope') THEN
        ALTER TABLE sys_role ADD CONSTRAINT ck_sys_role_data_scope
            CHECK (data_scope IN ('ALL', 'DEPT_AND_CHILD', 'DEPT', 'SELF'));
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS sys_permission (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(128) NOT NULL,
    name        VARCHAR(64)  NOT NULL,
    type        VARCHAR(16)  NOT NULL DEFAULT 'API',
    description VARCHAR(255) NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted     SMALLINT     NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1))
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_permission_code
    ON sys_permission (code) WHERE deleted = 0;

CREATE TABLE IF NOT EXISTS sys_menu (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id       BIGINT       NOT NULL DEFAULT 0,
    name            VARCHAR(64)  NOT NULL,
    path            VARCHAR(255) NOT NULL DEFAULT '',
    component       VARCHAR(255),
    redirect        VARCHAR(255),
    type            VARCHAR(16)  NOT NULL DEFAULT 'menu',
    title           VARCHAR(128) NOT NULL,
    icon            VARCHAR(128),
    permission_code VARCHAR(128),
    sort            INTEGER      NOT NULL DEFAULT 0,
    status          SMALLINT     NOT NULL DEFAULT 1 CHECK (status IN (0, 1)),
    visible         SMALLINT     NOT NULL DEFAULT 1 CHECK (visible IN (0, 1)),
    keep_alive      SMALLINT     NOT NULL DEFAULT 0 CHECK (keep_alive IN (0, 1)),
    affix_tab       SMALLINT     NOT NULL DEFAULT 0 CHECK (affix_tab IN (0, 1)),
    hide_in_menu    SMALLINT     NOT NULL DEFAULT 0 CHECK (hide_in_menu IN (0, 1)),
    link            VARCHAR(512),
    iframe_src      VARCHAR(512),
    badge           VARCHAR(32),
    badge_type      VARCHAR(16),
    badge_variants  VARCHAR(32),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted         SMALLINT     NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1)),
    CONSTRAINT ck_sys_menu_type CHECK (type IN ('catalog', 'menu', 'button', 'embedded', 'link'))
);
CREATE INDEX IF NOT EXISTS idx_sys_menu_parent ON sys_menu (parent_id);
CREATE INDEX IF NOT EXISTS idx_sys_menu_permission ON sys_menu (permission_code);

CREATE TABLE IF NOT EXISTS sys_user_role (
    user_id    BIGINT NOT NULL REFERENCES sys_user (id) ON DELETE CASCADE,
    role_id    BIGINT NOT NULL REFERENCES sys_role (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, role_id)
);
CREATE INDEX IF NOT EXISTS idx_sys_user_role_role ON sys_user_role (role_id);

CREATE TABLE IF NOT EXISTS sys_role_permission (
    role_id       BIGINT NOT NULL REFERENCES sys_role (id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES sys_permission (id) ON DELETE CASCADE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (role_id, permission_id)
);
CREATE INDEX IF NOT EXISTS idx_sys_role_permission_permission ON sys_role_permission (permission_id);

CREATE TABLE IF NOT EXISTS sys_role_menu (
    role_id    BIGINT NOT NULL REFERENCES sys_role (id) ON DELETE CASCADE,
    menu_id    BIGINT NOT NULL REFERENCES sys_menu (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (role_id, menu_id)
);
CREATE INDEX IF NOT EXISTS idx_sys_role_menu_menu ON sys_role_menu (menu_id);

CREATE TABLE IF NOT EXISTS pm_member (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_no  VARCHAR(32)  NOT NULL,
    username   VARCHAR(64)  NOT NULL,
    owner_id   BIGINT,
    nickname   VARCHAR(64)  NOT NULL DEFAULT '',
    phone      VARCHAR(32)  NOT NULL DEFAULT '',
    level      VARCHAR(16)  NOT NULL DEFAULT 'BASIC',
    points     INTEGER      NOT NULL DEFAULT 0 CHECK (points >= 0),
    balance    NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (balance >= 0),
    status     SMALLINT     NOT NULL DEFAULT 1 CHECK (status IN (0, 1)),
    joined_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    remark     VARCHAR(255) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted    SMALLINT     NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1)),
    CONSTRAINT ck_pm_member_level CHECK (level IN ('BASIC', 'SILVER', 'GOLD', 'PLATINUM'))
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_pm_member_no
    ON pm_member (member_no) WHERE deleted = 0;
ALTER TABLE pm_member ADD COLUMN IF NOT EXISTS owner_id BIGINT;
CREATE INDEX IF NOT EXISTS idx_pm_member_owner ON pm_member (owner_id);
CREATE INDEX IF NOT EXISTS idx_pm_member_username ON pm_member (username);
CREATE INDEX IF NOT EXISTS idx_pm_member_status ON pm_member (status);

CREATE TABLE IF NOT EXISTS pm_member_period (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  BIGINT      NOT NULL,
    period_no  VARCHAR(16) NOT NULL,
    start_at   TIMESTAMPTZ NOT NULL,
    end_at     TIMESTAMPTZ NOT NULL,
    status     VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'ACTIVE', 'EXPIRED', 'TERMINATED')),
    order_id   BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_pm_member_period_range CHECK (end_at > start_at)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_pm_member_period_no
    ON pm_member_period (member_id, period_no);
CREATE UNIQUE INDEX IF NOT EXISTS uk_pm_member_period_pending
    ON pm_member_period (member_id) WHERE status = 'PENDING';
CREATE UNIQUE INDEX IF NOT EXISTS uk_pm_member_period_order
    ON pm_member_period (order_id) WHERE order_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_pm_member_period_active
    ON pm_member_period (member_id, status, end_at);

ALTER TABLE pm_member_period DROP CONSTRAINT IF EXISTS pm_member_period_status_check;
ALTER TABLE pm_member_period ADD CONSTRAINT pm_member_period_status_check
    CHECK (status IN ('PENDING', 'ACTIVE', 'EXPIRED', 'TERMINATED'));

CREATE TABLE IF NOT EXISTS benefit_product (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_code    VARCHAR(64)  NOT NULL,
    name        VARCHAR(128) NOT NULL,
    description VARCHAR(2000) NOT NULL DEFAULT '',
    rules       VARCHAR(4000) NOT NULL DEFAULT '',
    status      SMALLINT     NOT NULL DEFAULT 1 CHECK (status IN (0, 1)),
    sort        INTEGER      NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_benefit_product_sku ON benefit_product (sku_code);

CREATE TABLE IF NOT EXISTS benefit_card (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no     VARCHAR(64) NOT NULL,
    product_sku  VARCHAR(64) NOT NULL,
    code_hash    VARCHAR(64) NOT NULL,
    code_cipher  TEXT        NOT NULL,
    code_mask    VARCHAR(64) NOT NULL,
    status       VARCHAR(16) NOT NULL DEFAULT 'UNUSED'
        CHECK (status IN ('UNUSED', 'CLAIMED', 'DISABLED')),
    expire_at    TIMESTAMPTZ,
    claimed_at   TIMESTAMPTZ,
    claimed_by   BIGINT,
    claim_id     BIGINT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_benefit_card_hash ON benefit_card (code_hash);
CREATE INDEX IF NOT EXISTS idx_benefit_card_stock
    ON benefit_card (product_sku, status, expire_at);
CREATE INDEX IF NOT EXISTS idx_benefit_card_batch ON benefit_card (batch_no);

CREATE TABLE IF NOT EXISTS benefit_claim (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id    BIGINT      NOT NULL,
    period_id    BIGINT      NOT NULL,
    product_sku  VARCHAR(64) NOT NULL,
    status       VARCHAR(16) NOT NULL DEFAULT 'PROCESSING'
        CHECK (status IN ('AVAILABLE', 'PROCESSING', 'SUCCESS', 'FAILED', 'UNKNOWN')),
    card_id      BIGINT,
    claimed_at   TIMESTAMPTZ,
    remark       VARCHAR(255) NOT NULL DEFAULT '',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_benefit_claim_period_sku
    ON benefit_claim (period_id, product_sku);
CREATE INDEX IF NOT EXISTS idx_benefit_claim_member
    ON benefit_claim (member_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_benefit_claim_status
    ON benefit_claim (period_id, status);

CREATE TABLE IF NOT EXISTS plan_version (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(64)  NOT NULL,
    name            VARCHAR(128) NOT NULL,
    price_cents     BIGINT       NOT NULL CHECK (price_cents >= 0),
    duration_days   INTEGER      NOT NULL DEFAULT 30 CHECK (duration_days > 0),
    ai_image_quota  INTEGER      NOT NULL DEFAULT 20 CHECK (ai_image_quota >= 0),
    ai_video_quota  INTEGER      NOT NULL DEFAULT 3 CHECK (ai_video_quota >= 0),
    benefit_quota   INTEGER      NOT NULL DEFAULT 2 CHECK (benefit_quota >= 0),
    status          SMALLINT     NOT NULL DEFAULT 1 CHECK (status IN (0, 1)),
    version_no      INTEGER      NOT NULL DEFAULT 1 CHECK (version_no > 0),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_plan_version_code_version
    ON plan_version (code, version_no);
CREATE UNIQUE INDEX IF NOT EXISTS uk_plan_version_active
    ON plan_version (code) WHERE status = 1;

CREATE TABLE IF NOT EXISTS orders (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no        VARCHAR(40)  NOT NULL,
    member_id       BIGINT       NOT NULL,
    user_id         BIGINT       NOT NULL,
    plan_version_id BIGINT       NOT NULL,
    amount_cents    BIGINT       NOT NULL CHECK (amount_cents >= 0),
    status          VARCHAR(16)  NOT NULL DEFAULT 'CREATED'
        CHECK (status IN ('CREATED', 'PAID', 'CANCELLED', 'REFUNDING', 'REFUNDED', 'CLOSED')),
    channel         VARCHAR(32)  NOT NULL DEFAULT 'MOCK',
    source          VARCHAR(32)  NOT NULL DEFAULT 'H5',
    purpose         VARCHAR(32)  NOT NULL DEFAULT 'MEMBER_PLAN',
    remark          VARCHAR(255) NOT NULL DEFAULT '',
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    paid_at         TIMESTAMPTZ,
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_orders_no ON orders (order_no);
CREATE UNIQUE INDEX IF NOT EXISTS uk_orders_unfinished
    ON orders (user_id, purpose) WHERE status IN ('CREATED', 'REFUNDING');
CREATE INDEX IF NOT EXISTS idx_orders_status_created ON orders (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_member ON orders (member_id, created_at DESC);

CREATE TABLE IF NOT EXISTS payment_transactions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_no       VARCHAR(64) NOT NULL,
    order_id     BIGINT      NOT NULL,
    channel      VARCHAR(32) NOT NULL,
    amount_cents BIGINT      NOT NULL CHECK (amount_cents >= 0),
    status       VARCHAR(16) NOT NULL DEFAULT 'SUCCESS'
        CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED')),
    raw_payload  TEXT        NOT NULL DEFAULT '',
    paid_at      TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_payment_txn_no ON payment_transactions (txn_no);
CREATE UNIQUE INDEX IF NOT EXISTS uk_payment_order_success
    ON payment_transactions (order_id) WHERE status = 'SUCCESS';
CREATE INDEX IF NOT EXISTS idx_payment_order ON payment_transactions (order_id, created_at DESC);

CREATE TABLE IF NOT EXISTS refunds (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_no    VARCHAR(40)  NOT NULL,
    order_id     BIGINT       NOT NULL,
    amount_cents BIGINT       NOT NULL CHECK (amount_cents >= 0),
    status       VARCHAR(16)  NOT NULL DEFAULT 'APPLIED'
        CHECK (status IN ('APPLIED', 'APPROVED', 'REJECTED', 'SUCCESS', 'FAILED')),
    operator     VARCHAR(64)  NOT NULL DEFAULT '',
    reason       VARCHAR(255) NOT NULL DEFAULT '',
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    processed_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_refunds_no ON refunds (refund_no);
CREATE UNIQUE INDEX IF NOT EXISTS uk_refunds_active
    ON refunds (order_id) WHERE status IN ('APPLIED', 'APPROVED');
CREATE INDEX IF NOT EXISTS idx_refunds_order ON refunds (order_id, created_at DESC);

CREATE TABLE IF NOT EXISTS sys_operation_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT,
    username    VARCHAR(64)  NOT NULL DEFAULT '',
    module      VARCHAR(64)  NOT NULL DEFAULT '',
    action      VARCHAR(64)  NOT NULL DEFAULT '',
    method      VARCHAR(16)  NOT NULL DEFAULT '',
    path        VARCHAR(255) NOT NULL DEFAULT '',
    params      TEXT         NOT NULL DEFAULT '',
    ip          VARCHAR(64)  NOT NULL DEFAULT '',
    user_agent  VARCHAR(512) NOT NULL DEFAULT '',
    success     SMALLINT     NOT NULL DEFAULT 1 CHECK (success IN (0, 1)),
    error_code  VARCHAR(64),
    cost_ms     BIGINT       NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_sys_operation_log_created ON sys_operation_log (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_sys_operation_log_user ON sys_operation_log (user_id);
